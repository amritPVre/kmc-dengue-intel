// Builds supabase/seed.sql: 16 boroughs, 144 wards (141 boundaries + 3 pending), two field
// teams per ward, and ward adjacency. Population is a placeholder (KMC average, ~31,000 per
// ward) until KMC or census ward figures are loaded.
import fs from 'node:fs';

const meta = JSON.parse(fs.readFileSync('src/data/ward-meta.json', 'utf8'));
const geo = JSON.parse(fs.readFileSync('data-raw/wards-seed.geojson', 'utf8'));
const geomByWard = new Map(geo.features.map((f) => [Number(f.properties.WARD), f.geometry]));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const out = [];
out.push('-- Generated by scripts/build-seed-sql.mjs — KMC geography, version 1 (144 wards)');
out.push('-- Boundaries: DataMeet Municipal_Spatial_Data (Kolkata), simplified. Verify against KMC official GIS.');
out.push('begin;');
out.push('insert into public.boroughs (geo_version, code, name) values');
out.push(Object.keys(meta.boroughs).map((b) => `  (1, ${q(b)}, ${q('Borough ' + b)})`).join(',\n') + '\non conflict do nothing;');
for (const w of Object.values(meta.wards)) {
  const g = geomByWard.get(w.ward);
  const geom = g ? `st_multi(st_setsrid(st_geomfromgeojson(${q(JSON.stringify(g))}), 4326))` : 'null';
  out.push(`insert into public.wards (geo_version, ward_no, borough, population, area_km2, geom, centroid, boundary_source) values (1, ${w.ward}, ${q(w.borough)}, 31000, ${w.areaKm2}, ${geom}, st_setsrid(st_makepoint(${w.centroid[0]}, ${w.centroid[1]}), 4326), ${q(w.boundary)}) on conflict do nothing;`);
}
out.push('insert into public.teams (ward_no, name) select ward_no, \'VCT-\' || ward_no || \'-\' || t from public.wards, unnest(array[\'A\', \'B\']) t where geo_version = 1 on conflict do nothing;');
out.push('select public.refresh_ward_neighbours(1::smallint);');
out.push('commit;');
fs.writeFileSync('supabase/seed.sql', out.join('\n') + '\n');
console.log('wrote supabase/seed.sql', (fs.statSync('supabase/seed.sql').size / 1024).toFixed(0), 'KB');
