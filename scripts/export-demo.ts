// Writes supabase/seed-demo.sql with the SYNTHETIC demo dataset (weather, cases, larval surveys,
// breeding sites, citizen reports) so a fresh Supabase project can be demonstrated end to end.
// Run: npx vite-node scripts/export-demo.ts
// Never load this file into a production database that holds real KMC data.
import fs from 'node:fs';
import { generateDemo } from '../src/lib/demo/generator';
import { todayIso } from '../src/lib/util';

const db = generateDemo(todayIso());
const q = (v: unknown) => (v == null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const chunks = <T,>(a: T[], n: number) => Array.from({ length: Math.ceil(a.length / n) }, (_, i) => a.slice(i * n, i * n + n));
const out: string[] = ['-- SYNTHETIC DEMO DATA — not real KMC figures. Generated by scripts/export-demo.ts', 'begin;'];

for (const w of db.wards) out.push(`update public.wards set population = ${w.population} where geo_version = 1 and ward_no = ${w.ward};`);
out.push('insert into public.weather_weekly (week_start, rain_mm, t_mean_c, rh_pct, source) values');
out.push(db.weather.map((w) => `(${q(w.weekStart)}, ${w.rainMm}, ${w.tMeanC}, ${w.rhPct}, 'synthetic')`).join(',\n') + '\non conflict (week_start) do nothing;');
for (const part of chunks(db.cases, 500)) {
  out.push('insert into public.dengue_cases (ward_no, reported_on, onset_on, test_type, source, age_band, sex, lat, lng, hospitalised, severity, dedupe_key) values');
  out.push(part.map((c) => `(${c.ward}, ${q(c.reportedOn)}, ${q(c.onsetOn)}, ${q(c.test)}, ${q(c.source)}, ${q(c.ageBand)}, ${q(c.sex)}, ${c.lat}, ${c.lng}, ${c.hospitalised}, ${q(c.severity)}, ${q(c.dedupeKey)})`).join(',\n') + '\non conflict (dedupe_key) do nothing;');
}
for (const part of chunks(db.surveys, 1000)) {
  out.push('insert into public.larval_surveys (ward_no, survey_date, team, houses_visited, houses_positive, containers_inspected, containers_positive) values');
  out.push(part.map((s) => `(${s.ward}, ${q(s.date)}, ${q(s.team)}, ${s.housesVisited}, ${s.housesPositive}, ${s.containersInspected}, ${s.containersPositive})`).join(',\n') + ';');
}
out.push('insert into public.breeding_sites (ward_no, site_type, lat, lng, status, detected_by, first_seen, last_action_on, description) values');
out.push(db.sites.map((s) => `(${s.ward}, ${q(s.type)}, ${s.lat}, ${s.lng}, ${q(s.status)}, ${q(s.detectedBy)}, ${q(s.firstSeen)}, ${q(s.lastActionOn ?? null)}, ${q(s.description)})`).join(',\n') + ';');
out.push('insert into public.citizen_reports (ward_no, kind, text, status, reported_at) values');
out.push(db.citizen.map((c) => `(${c.ward}, ${q(c.kind)}, ${q(c.text)}, ${q(c.status)}, ${q(c.reportedAt)})`).join(',\n') + ';');
out.push('commit;');
fs.writeFileSync('supabase/seed-demo.sql', out.join('\n') + '\n');
console.log(`wrote supabase/seed-demo.sql: ${db.cases.length} cases, ${db.surveys.length} surveys, ${db.sites.length} sites`);
